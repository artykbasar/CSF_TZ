#!/usr/bin/env python3
"""Build a minimal Vue 3 Yarn lock from the verified Frappe lock."""
import re
import shlex
import sys
from pathlib import Path


def entries(text):
    found = {}
    for block in re.split(r"\n\n+", text.strip()):
        head = block.splitlines()[0]
        if not head.endswith(":"):
            continue
        for selector in head[:-1].split(", "):
            found[selector.strip('"')] = block
    return found


def dependencies(block):
    active = False
    for line in block.splitlines()[1:]:
        if line == "  dependencies:" or line == "  optionalDependencies:":
            active = True
        elif line.startswith("  ") and not line.startswith("    "):
            active = False
        elif active and line.startswith("    "):
            name, version = shlex.split(line.strip())[:2]
            yield f"{name}@{version}"


def generate(source):
    lookup = entries(source)
    seed = "vue@3.5.43"
    if seed not in lookup:
        matches = [block for key, block in lookup.items()
                   if key.startswith("vue@") and 'version "3.5.43"' in block]
        if len(set(matches)) != 1:
            raise ValueError("Expected exactly one Vue 3.5.43 lock entry")
        block = matches[0]
        lookup[seed] = seed + ":" + block[block.find("\n"):]
    pending = [seed]
    included = {}
    while pending:
        selector = pending.pop()
        if selector in included:
            continue
        block = lookup.get(selector)
        if block is None:
            raise ValueError(f"Missing lock selector: {selector}")
        included[selector] = block
        pending.extend(dependencies(block))
    unique = {block.splitlines()[0]: block for block in included.values()}
    output = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n"
    output += "# yarn lockfile v1\n\n"
    output += "\n\n".join(unique[key] for key in sorted(unique)) + "\n"
    if "vuetify" in output.lower() or len(unique) < 8:
        raise ValueError("Vue lock closure invalid")
    return output


if __name__ == "__main__":
    original = Path(sys.argv[1]).read_text()
    print(generate(original), end="")
